/**
 * Maps subject name to standard template key
 */
export function getSubjectPromptKey(subjectName, reqSections = []) {
  const sub = (subjectName || '').toLowerCase().trim();
  const hasGrammarSection = Array.isArray(reqSections) && reqSections.some(s => 
    s.id?.startsWith('en2_') || 
    s.id?.includes('grammar') ||
    s.id?.includes('definition') ||
    s.title?.includes('সংজ্ঞাসহ') || 
    s.title?.includes('সংজ্ঞা') || 
    s.title?.includes('কাকে বলে') ||
    s.title?.includes('ব্যাকরণ')
  );
  if (sub.includes('ইংরেজি ২য়') || sub.includes('ইংরেজি ২') || sub.includes('english 2nd') || sub.includes('english 2') || sub.includes('grammar') || sub.includes('ব্যাকরণ') || (hasGrammarSection && (sub.includes('ইংরেজি') || sub.includes('english')))) return 'english_2nd';
  if (sub.includes('ইংরেজি') || sub.includes('english')) return 'english';
  if (sub.includes('বাংলা ২য়') || sub.includes('বাংলা ২') || sub.includes('bangla 2nd')) return 'bangla_2nd';
  if (sub.includes('বাংলা ১ম') || (sub.includes('বাংলা') && !sub.includes('২য়') && !sub.includes('2nd'))) return 'bangla_1st';
  if (sub.includes('গণিত') || sub.includes('math')) return 'math';
  if (sub.includes('বিজ্ঞান') || sub.includes('science')) return 'science';
  if (sub.includes('বিশ্বপরিচয়') || sub.includes('bgs') || sub.includes('বাংলাদেশ')) return 'bgs';
  if (sub.includes('ইসলাম') || sub.includes('islam')) return 'islam';
  if (sub.includes('হিন্দু') || sub.includes('hindu')) return 'hindu';
  if (sub.includes('সাধারণ জ্ঞান') || sub.includes('gk') || sub.includes('general knowledge') || sub.includes('জিকে')) return 'gk';
  if (sub.includes('কম্পিউটার') || sub.includes('computer') || sub.includes('ict') || sub.includes('আইসিটি')) return 'computer';
  return 'fallback';
}

/**
 * Storage key helper
 */
function getStorageKey(subjectKey, className = '') {
  const cleanClass = className ? className.trim() : 'default';
  return `custom_prompt_${cleanClass}_${subjectKey}`;
}

/**
 * Load customized prompt from localStorage or fallback to default template
 */
const PROMPT_STORAGE_VERSION = "v10_grounded";
export function loadCustomPrompt(subjectName, className = '', reqSections = []) {
  if (typeof window !== 'undefined') {
    const key = getSubjectPromptKey(subjectName, reqSections);
    
    // 1. Try class-specific custom prompt
    const classKey = getStorageKey(key, className);
    const classVal = localStorage.getItem(classKey);
    if (classVal && classVal.trim()) return classVal;

    // 2. Try global custom prompt for this subject
    const globalKey = getStorageKey(key, '');
    const globalVal = localStorage.getItem(globalKey);
    if (globalVal && globalVal.trim()) return globalVal;

    // 3. Fallback to default template
    return DEFAULT_PROMPT_TEMPLATES[key] || DEFAULT_PROMPT_TEMPLATES.fallback;
  }
  const key = getSubjectPromptKey(subjectName, reqSections);
  return DEFAULT_PROMPT_TEMPLATES[key] || DEFAULT_PROMPT_TEMPLATES.fallback;
}

/**
 * Save customized prompt to localStorage
 */
export function saveCustomPrompt(subjectName, className, promptText) {
  if (typeof window !== 'undefined') {
    const key = getSubjectPromptKey(subjectName);
    const storageKey = getStorageKey(key, className);
    if (promptText && promptText.trim()) {
      localStorage.setItem(storageKey, promptText.trim());
    } else {
      localStorage.removeItem(storageKey);
    }
  }
}

/**
 * Reset a subject prompt to default
 */
export function resetCustomPrompt(subjectName, className = '') {
  if (typeof window !== 'undefined') {
    const key = getSubjectPromptKey(subjectName);
    localStorage.removeItem(getStorageKey(key, className));
    localStorage.removeItem(getStorageKey(key, ''));
  }
}

/**
 * Check if a custom prompt has been edited
 */
export function isPromptCustomized(subjectName, className = '') {
  if (typeof window !== 'undefined') {
    const key = getSubjectPromptKey(subjectName);
    const classVal = localStorage.getItem(getStorageKey(key, className));
    const globalVal = localStorage.getItem(getStorageKey(key, ''));
    return Boolean(classVal || globalVal);
  }
  return false;
}

