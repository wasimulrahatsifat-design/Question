export function loadUniversalRules() {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('custom_prompt_universal_rules');
    return (saved && saved.trim()) ? saved : DEFAULT_UNIVERSAL_RULES;
  }
  return DEFAULT_UNIVERSAL_RULES;
}

/**
 * Save universal rules
 */
export function saveUniversalRules(text) {
  if (typeof window !== 'undefined') {
    if (text && text.trim()) {
      localStorage.setItem('custom_prompt_universal_rules', text.trim());
    } else {
      localStorage.removeItem('custom_prompt_universal_rules');
    }
  }
}

/**
 * Reset universal rules
 */
export function resetUniversalRules() {
  if (typeof window !== 'undefined') {
    localStorage.removeItem('custom_prompt_universal_rules');
  }
}
